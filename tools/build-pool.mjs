#!/usr/bin/env node
/* Builds courses/tech-pool.js from the NCVEC question pool (.docx).

   Usage: node tools/build-pool.mjs [source/technician-pool-2026.docx]

   Needs pandoc on the PATH. The output is committed, so the site itself
   has no build step. Re-run this only when a new pool or errata comes out. */
import { execFileSync } from 'node:child_process';
import { writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import path from 'node:path';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const src = process.argv[2] || path.join(root, 'source/technician-pool-2026.docx');
const out = path.join(root, 'courses/tech-pool.js');

const text = execFileSync('pandoc', ['-t', 'plain', '--wrap=none', src], { encoding: 'utf8', maxBuffer: 64 << 20 });
const lines = text.split('\n').map(l => l.trim());

/* The pool proper starts after the second "FCC Element 2 Question Pool" heading
   (the first one is the syllabus). */
const start = lines.findIndex(l => l === 'FCC Element 2 Question Pool');
if (start < 0) throw new Error('pool heading not found');
const end = lines.findIndex(l => /End of question pool text/.test(l));
const body = lines.slice(start, end < 0 ? undefined : end);

const subs = [];   // { id, name, questions, groups }
const groups = {}; // T1A -> description
const qs = [];
const HEAD = /^SUBELEMENT (T\d) - (.+?) \[(\d+) Exam Questions? - (\d+) Groups?\]/;
const GROUP = /^(T\d[A-Z]) (.+)$/;
const QID = /^(T\d[A-Z]\d{2}) ?\(([A-D])\) ?(?:\[(.+)\])?$/;
const OPT = /^([A-D])\. (.*)$/;

for (let i = 0; i < body.length; i++) {
  const l = body[i];
  if (!l) continue;
  let m;
  if ((m = HEAD.exec(l))) { subs.push({ id: m[1], name: m[2], exam: +m[3] }); continue; }
  if ((m = QID.exec(l))) {
    const q = { id: m[1], ans: m[2], rule: m[3] ? m[3].replace(/\s+/g, ' ').trim() : '', q: '', o: [] };
    let j = i + 1;
    const stem = [];
    for (; j < body.length && !OPT.test(body[j]); j++) if (body[j]) stem.push(body[j]);
    q.q = stem.join(' ');
    for (; j < body.length && body[j] !== '~~'; j++) {
      const om = OPT.exec(body[j]);
      if (om) q.o.push(om[2].trim());
      else if (body[j]) q.o[q.o.length - 1] += ' ' + body[j];
    }
    if (q.o.length !== 4) throw new Error(`${q.id}: expected 4 options, got ${q.o.length}`);
    qs.push(q); i = j; continue;
  }
  if ((m = GROUP.exec(l)) && !groups[m[1]]) { groups[m[1]] = m[2]; continue; }
}

/* Sanity checks */
const ids = new Set();
for (const q of qs) {
  if (ids.has(q.id)) throw new Error(`duplicate ${q.id}`);
  ids.add(q.id);
  if (!groups[q.id.slice(0, 3)]) throw new Error(`${q.id}: no group heading`);
}
const nGroups = Object.keys(groups).length;
const examTotal = subs.reduce((a, s) => a + s.exam, 0);
if (examTotal !== nGroups) throw new Error(`exam questions (${examTotal}) != groups (${nGroups})`);

const titleCase = s => s.toLowerCase().replace(/(^|[\s-])(\w)/g, (_, a, b) => a + b.toUpperCase()).replace(/’S\b/g, '’s').replace(/ And /g, ' and ');
const js = `"use strict";
/* GENERATED by tools/build-pool.mjs from ${path.basename(src)}. Do not edit by hand.
   2026-2030 Technician Class (FCC Element 2) question pool, effective 7/1/2026 to 6/30/2030,
   including the February 19, 2026 errata. Public domain (NCVEC Question Pool Committee).
   ${qs.length} questions, ${nGroups} groups, ${examTotal} questions per exam.

   Each question: id, ans (letter of the correct option, as published), rule (FCC Part 97
   reference, if any), q (question), o (options A to D in published order). */
const TECH_SUBELEMENTS = [
${subs.map(s => ' ' + JSON.stringify({ ...s, name: titleCase(s.name) })).join(',\n')}
];
const TECH_GROUPS = {
${Object.entries(groups).map(([k, v]) => ` ${k}: ${JSON.stringify(v)}`).join(',\n')}
};
const TECH_POOL = [
${qs.map(q => ' ' + JSON.stringify(q)).join(',\n')}
];
`;
writeFileSync(out, js);
console.log(`wrote ${path.relative(root, out)}: ${qs.length} questions, ${nGroups} groups, ${subs.length} subelements`);
